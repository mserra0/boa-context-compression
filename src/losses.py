import torch
import torch.nn.functional as F


def reconstruction_loss(
    logits: torch.Tensor,
    target_ids: torch.Tensor,
    attention_mask: torch.Tensor,
) -> torch.Tensor:
    """Cross-entropy reconstruction loss for ICAE autoencoding.

    Averages CE over valid (non-pad) token positions identified by attention_mask.

    Args:
        logits:         [B, I, V] — per-position logit distributions.
        target_ids:     [B, I]    — ground-truth context token IDs.
        attention_mask: [B, I]    — 1 at real tokens, 0 at left-padding.

    Returns:
        Scalar CE loss.
    """
    B, I, V = logits.shape
    per_token = F.cross_entropy(
        logits.reshape(B * I, V),
        target_ids.reshape(B * I),
        ignore_index=-100,
        reduction='none',
    ).reshape(B, I)
    valid = (attention_mask > 0).to(per_token.dtype)
    return (per_token * valid).sum() / valid.sum().clamp_min(1.0)


def valid_positions_mask(generated_ids: torch.Tensor, eos_token_ids) -> torch.Tensor:
    """Boolean [B, G] mask of supervised positions.

    Keeps every token up to AND INCLUDING the first end-of-sequence token in each
    row, and drops everything after it (the post-eos padding tail).

    This is eos-aware rather than pad-aware: Qwen's pad id (<|endoftext|>, 151643) is
    itself a valid eos, so a plain `generated_ids != pad` mask would wrongly drop a
    real stop token whenever the teacher ends a turn with <|endoftext|> instead of
    <|im_end|>. The first eos IS a training signal (the student must learn to stop);
    only the trailing pad is noise. Rows with no eos (teacher hit max_new_tokens) keep
    every position.

    Args:
        generated_ids:  [B, G] token IDs generated by the teacher.
        eos_token_ids:  int or iterable of ids the model treats as end-of-sequence.
    """
    if isinstance(eos_token_ids, int):
        eos_token_ids = [eos_token_ids]
    eos = torch.tensor(list(eos_token_ids), device=generated_ids.device)
    is_eos = (generated_ids.unsqueeze(-1) == eos).any(-1)   # [B, G]
    eos_seen = is_eos.cumsum(dim=1)                          # [B, G], inclusive
    # before the first eos (eos_seen == 0), plus the first eos itself (is_eos & ==1).
    return (eos_seen == 0) | (is_eos & (eos_seen == 1))


def kl_loss(
    student_logits: torch.Tensor,
    teacher_logits: torch.Tensor,
    generated_ids: torch.Tensor,
    temperature: float,
    eos_token_ids,
) -> torch.Tensor:
    """Token-uniform KL distillation loss.

    Weighted mean over supervised positions (up to and including the first eos),
    scaled by T² to preserve gradient magnitude after temperature softening
    (Hinton et al. 2015).

    Args:
        student_logits: [B, G, V] — raw logits from the student forward pass.
        teacher_logits: [B, G, V] — raw logits captured during teacher generation.
        generated_ids:  [B, G]    — token IDs generated by the teacher.
        temperature:    KD temperature (applied to both distributions).
        eos_token_ids:  end-of-sequence id(s); see valid_positions_mask.

    Returns:
        Scalar loss tensor.
    """
    valid = valid_positions_mask(generated_ids, eos_token_ids).to(student_logits.dtype)  # [B, G]
    per_tok_kl = F.kl_div(
        F.log_softmax(student_logits / temperature, dim=-1),
        F.softmax(teacher_logits / temperature, dim=-1),
        reduction='none',
    ).sum(-1)  # [B, G]
    return (per_tok_kl * valid).sum() / valid.sum().clamp_min(1.0) * (temperature ** 2)


def confidence_weighted_kl_loss(
    student_logits: torch.Tensor,
    teacher_logits: torch.Tensor,
    generated_ids: torch.Tensor,
    temperature: float,
    eos_token_ids,
    mode: str = "max_prob",
) -> torch.Tensor:
    """Confidence-weighted KL distillation loss.

    Like kl_loss, but positions where the teacher is confident (low entropy /
    high max probability) receive a proportionally larger weight. This directs
    gradient signal toward factual, low-ambiguity tokens (specific dates, names,
    numbers) and away from high-entropy filler that the teacher is indifferent
    about.

    Confidence is computed on the temperature-softened teacher distribution so
    that the weights are consistent with what the student is actually trained to
    match.

    Args:
        student_logits: [B, G, V]
        teacher_logits: [B, G, V]
        generated_ids:  [B, G]
        temperature:    KD temperature.
        eos_token_ids:  end-of-sequence id(s); positions after the first eos are
                        zeroed out before weighting (see valid_positions_mask).
        mode:
            "max_prob"    — weight = max(softmax(teacher / T)) per token.
                            Simple, no numerical issues, range [1/V, 1].
            "neg_entropy" — weight = 1 / (H(softmax(teacher / T)) + ε).
                            Strongly suppresses high-entropy positions.

    Returns:
        Scalar loss tensor on the same scale as kl_loss.
    """
    valid = valid_positions_mask(generated_ids, eos_token_ids).to(student_logits.dtype)  # [B, G]

    teacher_probs = F.softmax(teacher_logits / temperature, dim=-1)  # [B, G, V]

    if mode == "max_prob":
        weights = teacher_probs.max(dim=-1).values  # [B, G]
    elif mode == "neg_entropy":
        entropy = -(teacher_probs * (teacher_probs + 1e-9).log()).sum(-1)  # [B, G]
        weights = 1.0 / (entropy + 1e-6)
    else:
        raise ValueError(f"Unknown confidence mode: {mode!r}. Choose 'max_prob' or 'neg_entropy'.")

    weights = weights * valid  # zero pad positions
    denom = weights.sum().clamp_min(1e-9)

    per_tok_kl = F.kl_div(
        F.log_softmax(student_logits / temperature, dim=-1),
        teacher_probs,
        reduction='none',
    ).sum(-1)  # [B, G]

    return (per_tok_kl * weights).sum() / denom * (temperature ** 2)


def lm_ce_loss(
    student_logits: torch.Tensor,
    target_ids: torch.Tensor,
    target_mask: torch.Tensor,
) -> torch.Tensor:
    """Token-mean cross-entropy for the LM-pretraining continuation objective.

    student_logits[b, i] predicts target_ids[b, i] (the slice in the forward already
    applied the −1 shift). Averages over real Y positions (target_mask == 1) and is
    NaN-safe when a row is fully padded.

    Args:
        student_logits: [B, G, V] raw logits aligned with the Y target positions.
        target_ids:     [B, G] continuation token IDs (Qwen vocab).
        target_mask:    [B, G] 1 = real Y token, 0 = right-padding.
    """
    B, G, V = student_logits.shape
    mask = target_mask.to(student_logits.dtype)  # [B, G]
    per_tok = F.cross_entropy(
        student_logits.reshape(-1, V),
        target_ids.reshape(-1),
        reduction="none",
    ).reshape(B, G)  # [B, G]
    return (per_tok * mask).sum() / mask.sum().clamp_min(1.0)
